import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

export const task=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const base=path.join(task,'engine/rules');
const generated=path.join(base,'arkham-core/generated/Arkham/Native/SourceIdentity.hs');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
function walk(relative){
 const dir=path.join(base,relative),stat=fs.lstatSync(dir);
 if(stat.isSymbolicLink()||!stat.isDirectory())throw Error('Not an ordinary input directory: '+relative);
 return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>{
  const r=relative+'/'+e.name,s=fs.lstatSync(path.join(base,r));
  if(s.isSymbolicLink())throw Error('Reparse/symbolic source input rejected: '+r);
  if(s.isDirectory())return walk(r);
  if(!s.isFile())throw Error('Non-file source input: '+r);
  return [r];
 });
}
export function identity(){
 const roots=['arkham-core/library','cards-discover/app','cards-discover/library'];
 const sources=roots.flatMap(walk).filter(r=>/\.hs(?:-boot)?$/.test(r));
 const data=walk('arkham-core/data');
 const expected=['cards.json','community-starter-decks.json','cycles.json','arkham/cycles/nightOfTheZealot.json','arkham/scenarios/nightOfTheZealot/theGathering.json','arkham/sets/theGathering.json'];
 if(JSON.stringify([...data].sort())!==JSON.stringify(expected.map(p=>'arkham-core/data/'+p).sort()))throw Error('Expected exact six published data paths');
 const nativeData=walk('arkham-core/native-data');
 if(JSON.stringify(nativeData)!==JSON.stringify(['arkham-core/native-data/deckbuild-catalog.json','arkham-core/native-data/deckbuild-taboos.json','arkham-core/native-data/settings-catalog.json']))throw Error('Expected exact reviewed native settings, Build and taboo data paths');
 const configs=['stack.yaml','stack.yaml.lock','arkham-core/package.yaml','cards-discover/package.yaml'];
 const names=[...sources,...data,...nativeData,...configs].sort();
 const lower=new Set(); const files=[];
 for(const name of names){
  if(name.includes('..')||name.includes('\\')||path.isAbsolute(name)||lower.has(name.toLowerCase()))throw Error('Ambiguous source input '+name);
  lower.add(name.toLowerCase());
  const p=path.join(base,name),s=fs.lstatSync(p);if(!s.isFile()||s.isSymbolicLink())throw Error('Unsafe source input '+name);
  const bytes=fs.readFileSync(p);files.push({path:name,bytes:bytes.length,sha256:sha(bytes)});
 }
 // JSON arrays provide unambiguous path/size/hash framing; raw file bytes are
 // hashed without newline/encoding normalization. Algorithm has a fixed domain.
 const definition={algorithm:'arkham-core-source-sha256-v1',compatibilityPolicy:1,publishedBaseline:'8e2f6798598d426406eb8479f16c289d37a9359d275ecd38bc1bb9494fe0f681',compiler:'ghc-9.14.1',gitSha1Constant:'f6ed09bec346ebc505ade739d34a7aea3305fa5c',files};
 const sourceId='arkham-core-sha256:'+sha(Buffer.from(JSON.stringify(definition),'utf8'));
 return {sourceId,definition,sourceCount:sources.length,dataPaths:data.sort(),nativeDataPaths:nativeData};
}
function moduleText(id){return '-- Generated by src/core-identity.mjs; do not edit.\nmodule Arkham.Native.SourceIdentity (coreSourceId) where\nimport Data.Text (Text)\ncoreSourceId :: Text\ncoreSourceId = "'+id+'"\n';}
export function verifyIdentity(){
 const current=identity();
 if(fs.readFileSync(generated,'utf8')!==moduleText(current.sourceId))throw Error('Generated source identity is stale');
 const files=walk('arkham-core/generated');
 if(files.length!==1||path.resolve(base,files[0])!==generated)throw Error('Unexpected generated source input');
 if(fs.existsSync(path.join(base,'arkham-core/library/Arkham/Native/SourceIdentity.hs')))throw Error('Duplicate SourceIdentity module');
 return {...current,generatedSha256:sha(fs.readFileSync(generated))};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const [mode,name]=process.argv.slice(2);
 if(!['generate','verify'].includes(mode))throw Error('generate/verify required');
 if(mode==='generate'){
  if(!/^phase2-identity-r\d+$/.test(name??''))throw Error('Named identity receipt required');
  const report=path.join(task,'reports',name+'.json');if(fs.existsSync(report))throw Error('Identity receipt already exists');
  fs.mkdirSync(path.dirname(report),{recursive:true});
  const before=identity();fs.mkdirSync(path.dirname(generated),{recursive:true});
  if(fs.existsSync(generated)&&!fs.readFileSync(generated,'utf8').startsWith('-- Generated by src/core-identity.mjs; do not edit.'))throw Error('Refuse unrelated generated module');
  fs.writeFileSync(generated,moduleText(before.sourceId));
  const checked=verifyIdentity();if(checked.sourceId!==before.sourceId)throw Error('Inputs changed while generating');
  fs.writeFileSync(report,JSON.stringify({...checked,scope:'Source/data compatibility identity, not binary reproducibility/security signature',passed:true},null,2),{flag:'wx'});
  console.log(JSON.stringify({passed:true,sourceId:checked.sourceId,inputs:checked.definition.files.length,report}));
 } else {const checked=verifyIdentity();console.log(JSON.stringify({passed:true,sourceId:checked.sourceId,inputs:checked.definition.files.length}));}
}
